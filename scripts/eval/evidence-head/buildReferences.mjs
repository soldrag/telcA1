/**
 * Builds the evidence head's reference vectors for every app task: src/data/exams/evidence-head/<task>.json
 * (unique phrase vectors as int16, units and purpose prototypes as indices) and the lazy registry index.js.
 *   node --import ./tests/support/loadLexiconData.js scripts/eval/evidence-head/buildReferences.mjs
 * Rebuild after a change of rubric aspects, example phrases, example bank or the embedding model.
 */

import fs from 'node:fs';
import { openVectorStore } from './vectorStore.mjs';
import { loadTasks, TASK_IDS } from './headModel.mjs';
import { encodeReferenceVector, hashPhrases } from '../../../src/services/schreiben/grading/evidenceHead/referenceVectors.js';
import { indexTaskPhrases } from '../../../src/services/schreiben/grading/evidenceHead/taskReferences.js';

const OUT = new URL('../../../src/data/exams/evidence-head/', import.meta.url);
fs.mkdirSync(OUT, { recursive: true });

const tasks = await loadTasks();
const store = await openVectorStore();
for (const id of TASK_IDS) {
  const task = tasks[id];
  const indexed = indexTaskPhrases({ task, bank: task.bank, examples: task.examples });
  const vectors = await store.embed(indexed.texts);
  const stored = { version: 1, task: id, phrases: hashPhrases(indexed.texts), vectors: vectors.map(encodeReferenceVector), groups: indexed.groups, purpose: indexed.purpose };
  fs.writeFileSync(new URL(`${id}.json`, OUT), `${JSON.stringify(stored)}\n`);
  console.log(id, indexed.texts.length, 'phrases');
}
store.close();

const loaders = TASK_IDS.map((id) => `  '${id}': () => import('./${id}.json', { with: { type: 'json' } }),`).join('\n');
fs.writeFileSync(new URL('index.js', OUT), `/**
 * Lazy registry of the evidence head's precomputed reference vectors per task (generated by
 * scripts/eval/evidence-head/buildReferences.mjs; do not edit). Each task's vectors load on its first grading.
 */

const LOADERS = {
${loaders}
};

/** @returns {Promise<object|null>} the stored references of a task, null when none were built */
export async function loadStoredTaskReferences(taskId) {
  const load = LOADERS[taskId];
  return load ? (await load()).default : null;
}
`);
